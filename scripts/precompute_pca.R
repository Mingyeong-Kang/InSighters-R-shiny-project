# =============================================================================
# precompute_pca.R — PCA 를 한 번 계산해 data/pca_cache.rds 로 저장 + 정확성 검증
# 실행 (프로젝트 루트에서):  Rscript scripts/precompute_pca.R
# 앱은 이 캐시를 읽기만 하므로 시작이 빠릅니다. shoes/ 가 바뀌면 다시 실행하세요.
# =============================================================================
for (f in c("config.R", "image_utils.R", "pca_engine.R")) source(file.path("R", f), encoding = "UTF-8")

t0 <- Sys.time()
cat_data <- load_catalogue_matrix()
cat(sprintf("Loaded %d photos × %d pixels\n", nrow(cat_data$X), ncol(cat_data$X)))
pca <- build_pca(cat_data$X, cat_data$meta)
cat(sprintf("PCA done in %.1fs\n", as.numeric(difftime(Sys.time(), t0, units = "secs"))))

# ---- 검증 1: loadings 직교정규성, 점수 = Xc V -------------------------------
v <- verify_pca(pca)
cat(sprintf("max |VᵀV − I|      = %.2e\n", v$orthonormal_max_error))
cat(sprintf("max |XcV − scores| = %.2e\n", v$score_max_error))

# ---- 검증 2: prcomp 와 분산비율 비교 (처음 5개) -----------------------------
pr <- prcomp(cat_data$X, center = TRUE, scale. = FALSE, rank. = 5)
ve_pr <- pr$sdev^2 / sum(pr$sdev^2)
cat("variance ratio (ours)  :", round(pca$var_ratio[1:5], 5), "\n")
cat("variance ratio (prcomp):", round(ve_pr[1:5], 5), "\n")
cat(sprintf("|cor| of PC1 scores with prcomp = %.6f\n", abs(cor(pca$scores[, 1], pr$x[, 1]))))

# ---- 검증 3: 복원 — K 가 커질수록 오차 감소, 모든 PC 사용 시 원본과 거의 일치 -------
x <- cat_data$X[1, ]; z <- project_photo(pca, x)
for (K in c(1, 10, 50, ncol(pca$loadings))) {
  cat(sprintf("rebuild RMSE (photo 1, K=%3d) = %.5f\n", K, sqrt(mean((reconstruct(pca, z, K) - x)^2))))
}

# ---- 검증 4: selfcheck (카탈로그에 없는 사진) 정답 여부, 여러 K ------------------
lab <- utils::read.csv(file.path(PATH_SELFCHECK, "labels.csv"), stringsAsFactors = FALSE)
sc_rows <- lapply(c(5, 10, 20, 30, 50, 100), function(K) {
  ok <- vapply(seq_len(nrow(lab)), function(i) {
    x <- mat_to_vec(read_gray(file.path(PATH_SELFCHECK, lab$photo[i])))
    search_similar(pca, x, K)$prediction == lab$category[i]
  }, logical(1))
  data.frame(K = K, correct = sum(ok), total = length(ok),
             detail = paste(sprintf("%s:%s", sub("selfcheck_", "", sub("\\.png$", "", lab$photo)),
                                    ifelse(ok, "O", "X")), collapse = " "))
})
sc <- do.call(rbind, sc_rows)
print(sc)

# ---- 추가: LOO Top-5 정확도 (K = 1~100) ---------------------------------------
cat("Computing leave-one-out accuracy for K = 1..100 ...\n")
pca$loo_accuracy <- loo_accuracy(pca)
print(pca$loo_accuracy[pca$loo_accuracy$K %in% c(1, 5, 10, 20, 30, 40, 50, 75, 100), ])
best <- pca$loo_accuracy[which.max(pca$loo_accuracy$accuracy), ]
cat(sprintf("Best LOO accuracy %.4f at K = %d\n", best$accuracy, best$K))

# ---- 검증 결과를 data/pca_verification.md 로 저장 (숫자만, 신발 데이터 아님 -> 커밋 가능) ----
dir.create("data", showWarnings = FALSE)
writeLines(c(
  "# PCA verification (generated by scripts/precompute_pca.R)", "",
  sprintf("- Generated: %s", format(Sys.time(), "%Y-%m-%d %H:%M")),
  sprintf("- Catalogue: %d photos x %d pixels, %d PCs stored", nrow(pca$X), ncol(pca$X), ncol(pca$loadings)),
  sprintf("- max |V'V - I| = %.2e, max |XcV - scores| = %.2e", v$orthonormal_max_error, v$score_max_error),
  sprintf("- Variance ratio PC1-5 (ours):   %s", paste(round(pca$var_ratio[1:5], 5), collapse = ", ")),
  sprintf("- Variance ratio PC1-5 (prcomp): %s", paste(round(ve_pr[1:5], 5), collapse = ", ")),
  sprintf("- Cumulative variance K=10/20/30/50/100: %s",
          paste(sprintf("%.1f%%", 100 * pca$cum_ratio[c(10, 20, 30, 50, 100)]), collapse = " / ")),
  "", "## Self-check (Top-5 vote)", "", "| K | correct | detail |", "|---|---|---|",
  sprintf("| %d | %d / %d | %s |", sc$K, sc$correct, sc$total, sc$detail),
  "", "## Leave-one-out accuracy (catalogue, Top-5 vote)", "", "| K | accuracy |", "|---|---|",
  with(pca$loo_accuracy[pca$loo_accuracy$K %in% c(1, 5, 10, 20, 30, 40, 50, 75, 100), ],
       sprintf("| %d | %.1f%% |", K, 100 * accuracy)),
  "", sprintf("Best: %.1f%% at K = %d", 100 * best$accuracy, best$K)
), file.path("data", "pca_verification.md"))

saveRDS(pca, PATH_PCA_CACHE, compress = TRUE)
cat(sprintf("Saved %s (%.1f MB) and data/pca_verification.md in %.1fs total\n", PATH_PCA_CACHE,
            file.size(PATH_PCA_CACHE) / 1e6, as.numeric(difftime(Sys.time(), t0, units = "secs"))))
